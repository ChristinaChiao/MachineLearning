from transformers import AutoTokenizer, AutoModelForQuestionAnswering
import torch

ckpt = "distilbert-base-cased-distilled-squad"
tokenizer = AutoTokenizer.from_pretrained(ckpt)
model = AutoModelForQuestionAnswering.from_pretrained(ckpt)

context = """
Hugging Face was founded in 2016 by Clément Delangue,
Julien Chaumond and Thomas Wolf. The company is
headquartered in New York City and has become the
leading open-source platform for machine learning.
"""

questions = [
    "When was Hugging Face founded?",
    "Who founded Hugging Face?",
    "Where is Hugging Face headquartered?"
]

for q in questions:
    # 1) Tokenize question and context
    inputs = tokenizer(q, context, return_tensors="pt", truncation=True)

    # 2) Model inference
    with torch.no_grad():
        outputs = model(**inputs)

    # 3) Get the answer span
    answer_start_scores = outputs.start_logits
    answer_end_scores = outputs.end_logits

    # Get the most likely beginning and end of the answer span
    answer_start = torch.argmax(answer_start_scores)
    answer_end = torch.argmax(answer_end_scores) + 1  # +1 to include the end token

    # Convert tokens to answer string
    answer = tokenizer.convert_tokens_to_string(tokenizer.convert_ids_to_tokens(inputs['input_ids'][0][answer_start:answer_end]))

    # Calculate score (optional, can be more complex)
    score = (torch.max(torch.softmax(answer_start_scores, dim=-1)) + torch.max(torch.softmax(answer_end_scores, dim=-1))) / 2

    print(f"Q: {q}")
    print(f"A: {answer} (score={score:.3f})\n")

