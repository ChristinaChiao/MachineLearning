# ====== 1. 匯入套件 ======
import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.utils.data import DataLoader
from torchvision import datasets, transforms

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
torch.manual_seed(42)

# ====== 2. 載入 MNIST ======
transform = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize((0.1307,), (0.3081,)),
])
train_set = datasets.MNIST("./data", train=True,  download=True, transform=transform)
test_set  = datasets.MNIST("./data", train=False, download=True, transform=transform)
train_loader = DataLoader(train_set, batch_size=128,  shuffle=True,  num_workers=2)
test_loader  = DataLoader(test_set,  batch_size=1000, shuffle=False, num_workers=2)

# ====== 3. 簡單 CNN 模型 ======
class CNN(nn.Module):
    def __init__(self):
        super().__init__()
        self.conv1 = nn.Conv2d(1,  32, kernel_size=3, padding=1)
        self.conv2 = nn.Conv2d(32, 64, kernel_size=3, padding=1)
        self.fc1   = nn.Linear(64 * 7 * 7, 128)
        self.fc2   = nn.Linear(128, 10)
        self.drop  = nn.Dropout(0.25)

    def forward(self, x):
        x = F.max_pool2d(F.relu(self.conv1(x)), 2)   # 28→14
        x = F.max_pool2d(F.relu(self.conv2(x)), 2)   # 14→7
        x = x.flatten(1)
        x = F.relu(self.fc1(x))
        x = self.drop(x)
        return self.fc2(x)

# ====== 4. 一次定義七種優化器 ======
def make_optimizer(name, params):
    if name == "SGD":
        return torch.optim.SGD(params, lr=0.01)
    elif name == "Momentum":
        return torch.optim.SGD(params, lr=0.01, momentum=0.9)
    elif name == "NAG":
        return torch.optim.SGD(params, lr=0.01,
                               momentum=0.9, nesterov=True)
    elif name == "RMSProp":
        return torch.optim.RMSprop(params, lr=0.001, alpha=0.9)
    elif name == "Adam":
        return torch.optim.Adam(params, lr=0.001,
                                betas=(0.9, 0.999))
    elif name == "AdamW":
        return torch.optim.AdamW(params, lr=0.001,
                                 weight_decay=0.01)
    elif name == "NAdam":
        return torch.optim.NAdam(params, lr=0.001)
    else:
        raise ValueError(name)

# ====== 5. 訓練與評估函式 ======
def train_one_epoch(model, loader, optimizer):
    model.train()
    total_loss = 0
    for x, y in loader:
        x, y = x.to(device), y.to(device)
        optimizer.zero_grad()
        loss = F.cross_entropy(model(x), y)
        loss.backward()
        optimizer.step()
        total_loss += loss.item() * x.size(0)
    return total_loss / len(loader.dataset)

def evaluate(model, loader):
    model.eval()
    correct = 0
    with torch.no_grad():
        for x, y in loader:
            x, y = x.to(device), y.to(device)
            pred = model(x).argmax(1)
            correct += (pred == y).sum().item()
    return correct / len(loader.dataset)

# ====== 6. 七個優化器同台 PK ======
optim_names = ["SGD", "Momentum", "NAG",
               "RMSProp", "Adam",
               "AdamW", "NAdam"]
EPOCHS = 10
results = {}

for name in optim_names:
    print(f"=== Training with {name} ===")
    torch.manual_seed(42)             # 同初始化
    model = CNN().to(device)
    optimizer = make_optimizer(name, model.parameters())

    train_losses, test_accs = [], []
    for ep in range(1, EPOCHS + 1):
        loss = train_one_epoch(model, train_loader, optimizer)
        acc  = evaluate(model, test_loader)
        train_losses.append(loss)
        test_accs.append(acc)
        print(f"  ep {ep:2d} | loss {loss:.4f} | acc {acc*100:.2f}%")

    results[name] = {"loss": train_losses,
                     "acc":  test_accs}

# ====== 7. 繪圖比較 ======
import matplotlib.pyplot as plt
fig, axes = plt.subplots(1, 2, figsize=(14, 5))
for name, hist in results.items():
    axes[0].plot(hist["loss"], label=name)
    axes[1].plot(hist["acc"],  label=name)
axes[0].set_title("Train Loss"); axes[0].legend()
axes[1].set_title("Test Accuracy"); axes[1].legend()
plt.savefig("optimizer_comparison.png", dpi=150)

