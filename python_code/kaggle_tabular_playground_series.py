# ────────────────────────────────────────────
# Step 1: 載入需要的函式庫
# ────────────────────────────────────────────

# 資料處理
import pandas as pd
import numpy  as np
from pathlib import Path

# 預處理：標準化與降維
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition  import PCA

# 分群演算法（Scikit-learn 兩款主力）
from sklearn.cluster        import KMeans
from sklearn.mixture        import GaussianMixture

# 隨機種子，確保結果可重現
SEED = 42
np.random.seed(SEED)

# Step 2: 載入資料並做最基本的 EDA

DATA_PATH = Path(__file__).resolve().parent / "data.csv"
if not DATA_PATH.is_file():
    raise FileNotFoundError(f"找不到資料檔：{DATA_PATH}")
if DATA_PATH.stat().st_size == 0:
    raise ValueError(f"資料檔是空的：{DATA_PATH}。請將有效的競賽 data.csv 放回此路徑。")

df = pd.read_csv(DATA_PATH)

print(f"資料形狀：{df.shape}")
print(f"欄位名稱：{df.columns.tolist()[:5]} ...")
print(f"缺失值總數：{df.isnull().sum().sum()}")

# 預期輸出：
# 資料形狀：(98000, 30)   # 1 個 id + 29 個 f_xx
# 欄位名稱：['id', 'f_00', 'f_01', 'f_02', 'f_03'] ...
# 缺失值總數：0

# 把 id 抽出來，特徵留下來做模型用
ids      = df["id"].copy()
features = df.drop(columns=["id"]).copy()

# Silhouette 偏好 2-4 個大群，未必能最佳化本賽的 ARI；離散欄位另有較強的群集結構。
int_cols = features.select_dtypes(include="int").columns.tolist()
if not int_cols:
    raise ValueError("找不到整數型特徵，請確認 data.csv 欄位格式。")

print(f"整數型特徵：{int_cols}")

# 主候選：在 f_07..f_13 標準化後做 7 群 KMeans。
X_int = StandardScaler().fit_transform(features[int_cols])
kmeans = KMeans(n_clusters=7, n_init=50, random_state=SEED)
labels_kmeans = kmeans.fit_predict(X_int)

# 替代候選：全特徵 PCA 10 維後，以對角共變異數 GMM 分 7 群。
X_scaled = StandardScaler().fit_transform(features)
X_pca10 = PCA(n_components=10, random_state=SEED).fit_transform(X_scaled)
gmm = GaussianMixture(
    n_components=7,
    covariance_type="diag",
    n_init=5,
    reg_covar=1e-5,
    max_iter=300,
    random_state=SEED,
)
labels_gmm = gmm.fit_predict(X_pca10)

def write_submission(labels, filename):
    submission = pd.DataFrame({"id": ids, "Predicted": labels.astype(int)})
    assert len(submission) == len(df), "列數不一致！"
    assert submission.isnull().sum().sum() == 0, "有缺失值！"
    assert list(submission.columns) == ["id", "Predicted"], "欄位名稱錯誤！"
    output_path = DATA_PATH.parent / filename
    submission.to_csv(output_path, index=False)
    print(f"{output_path.name}: {len(submission):,} 筆，{submission['Predicted'].nunique()} 群")

write_submission(labels_kmeans, "submission.csv")
write_submission(labels_gmm, "submission_gmm_pca10.csv")

